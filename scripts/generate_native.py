"""Generate stable plugin symbols from the frozen 0.2.1 expression ABI.

The input permutation and Struct names are intentionally independent of upstream
metadata: namespace receiver order is part of our existing Python API.
"""
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]


def generate():
    api = json.loads((ROOT / 'scripts/api.json').read_text())
    abi = json.loads((ROOT / 'scripts/plugin_abi.json').read_text())
    lines = ['// Generated by scripts/generate_native.py. Do not edit.',
             'use polars::prelude::*;', 'use pyo3_polars::derive::polars_expr;',
             'use ta_lib::abstract_api::FuncId;',
             'use crate::{missing::Masked, native::{Params, compute}};']
    for f in api:
        name = f['name']
        fields = abi[name]['fields']
        types = ['Float64' if o['type'] == 'double' else 'Int32' for o in f['outputs']]
        if fields:
            schema = ', '.join(f'Field::new("{n}", DataType::{t})' for n, t in zip(fields, types))
            lines += [f'fn {name}_output(_: &[Field]) -> PolarsResult<Field> {{',
                      f'Ok(Field::new("", DataType::Struct(vec![{schema}])))', '}',
                      f'#[polars_expr(output_type_func={name}_output)]']
        else:
            lines += [f'#[polars_expr(output_type={types[0]})]']
        order = ', '.join(map(str, abi[name]['order']))
        names = ', '.join(f'"{n}"' for n in fields)
        lines += [f'fn {name}(inputs: &[Series], kwargs: Masked<Params>) -> PolarsResult<Series> {{',
                  f'kwargs.apply(inputs, |params| compute(FuncId::{name.upper()}, inputs, &params, &[{order}], &[{names}]))', '}']
    path = ROOT / 'src/generated.rs'
    path.write_text('\n'.join(lines) + '\n')
    subprocess.run(['rustfmt', '--edition', '2021', str(path)], check=True)


if __name__ == '__main__':
    generate()
